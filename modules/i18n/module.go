// Package i18n wires **the distribution's own copy** into the kernel's message catalogs.
//
// # Why it is needed
//
// The kernel knows only its own module names. The distribution's modules -- client takeover,
// upstream quirk patches, the UI -- it does not recognize one sentence of what they say: those
// messages are neither in the kernel's ledger nor in the kernel's catalogs. The opening the kernel
// offers is `lib/i18n.Extend`, and note it is **append**, not install: installing (`Install`) is
// modules/locale's job and happens exactly once per assembly (it resolves the language and
// installs the tables); appending only merges **new** ids in.
//
// # Why it is a weak dependency (Optional)
//
// The "which language does this process speak" layer is optional: the skeleton distribution
// (dist-hello.json) turns every kernel module off with `"disable": ["*"]`, and not even
// modules/locale is in the graph. Then nothing here should happen -- there is no language to
// install, the copy is the English sentence in the source (the kernel's identity path), and "the
// language layer removed" should not keep the whole distribution from assembling.
//
// Declaring the dependency Optional also buys **start order**: when modules/locale is present, it
// starts before this one (Extend must be called after Install, otherwise it appends into a table
// that is not installed yet).
//
// # Where the catalogs come from
//
// Two files under `catalogs/`: `ledger.json` is generated by `tools/i18n extract` scanning the
// source (which messages, where, with what arguments), `<tag>.json` is the translations. Both are
// version-controlled, and CI's ratchet (`testing/i18n_test.go`) watches them -- this file only
// embeds them and appends once locale is ready. **Adding a message is not a change here**: write
// `i18n.T("English", …)`, then run `tools/i18n extract` and `tools/i18n sync`.
package i18n

import (
	"context"
	"embed"
	"io/fs"

	localeapi "github.com/rzbdz/newgate-ext/modules/locale"
	modules "github.com/rzbdz/newgate/component"
	corei18n "github.com/rzbdz/newgate/lib/i18n"
)

// What is embedded is the **bundle (.bin)**, not JSON -- for exactly the same reason as the
// kernel's copy (see the kernel's lib/i18n/catalogs.go and bundle.go): every `newgate …` command
// reads these tables, and parsing JSON is the most expensive item in that assembly. JSON remains
// the single truth, the two are kept in step by `tools/i18n bundle`, and CI and the tests stop
// "changed the JSON, forgot to regenerate".
//
//go:embed catalogs/*.bin
var catalogsFS embed.FS

// CatalogDir is the embedded directory's path inside the FS.
//
// It is **one constant** rather than a literal written everywhere: where the tool generates to,
// where the ratchet test reads, and where the process embeds must be the same place -- a mismatch
// shows up as "the file is there but it is empty at runtime", and that is only visible when some
// message goes untranslated.
const CatalogDir = "catalogs"

// Name is this module's name in the assembly table and in `newgate plugin`.
const Name = "i18n"

// New declares this component: at start, merge the distribution's own ledger and translations into
// the language the kernel already installed.
//
// It has no Stop: the append is one-shot and carries no ownership to undo (`Extend` adds a copy of
// the data and holds no handle). That is not an omission -- the component framework only asks that
// "whatever you took, give it back in Stop", and nothing is taken here.
func New() modules.Component {
	return modules.Component{
		Name: Name,
		Desc: func() string {
			return corei18n.T("this distribution's message catalog, appended to the installed language", nil)
		},
		// The vocabulary belongs to the product layer (see component.Type's comment): copy is part of
		// the infrastructure layer.
		Type:     "infra",
		Requires: []modules.Requirement{modules.Optional(localeapi.Capability)},
		Start:    start,
	}
}

func start(_ context.Context, ctx modules.Context) error {
	// Without the language layer there is no "which language this run speaks": appending is
	// meaningless, and **must not** be meaningful -- the source-language path is the identity, and
	// the sentence written in the code is the final text.
	if _, ok := modules.Get(ctx, localeapi.Capability); !ok {
		return nil
	}

	raw, err := fs.ReadFile(catalogsFS, CatalogDir+"/"+corei18n.LedgerBundleName)
	if err != nil {
		// The ledger is embedded in this very package; failing to read it can only be a packaging
		// mistake -- report it, do not go silent.
		return err
	}
	led, err := corei18n.DecodeLedger(raw)
	if err != nil {
		return err
	}
	cats, err := corei18n.BundlesFromFS(catalogsFS, CatalogDir)
	if err != nil {
		return err
	}
	// An empty catalog is **legal** (this distribution has no copy of its own today): there is
	// nothing to append, and that is behaviorally the same thing as "append succeeded" -- the
	// source-language path is the identity.
	//
	// **Deliberately no log line here**: Start runs on **every `newgate …` command** (the CLI
	// assembles a graph of its own too), so printing a line here adds noise to every command.
	// Visibility lives elsewhere: `newgate lang` reports coverage, doctor reports gaps. Hit for real
	// on 2026-09-20 -- one release printed `[i18n] 225 messages appended…` before every command
	// typed.
	if err := corei18n.Extend(led, cats); err != nil {
		return err
	}
	return nil
}
